--INSERT Procedures: Create stored procedures to insert records into STUDENT tables (SP_INSERT_STUDENT) --
CREATE PROCEDURE SP_INSERT_STUDENT
    @STDID INT,
    @SNAME VARCHAR(50),
    @CITY VARCHAR(50),
    @SPI DECIMAL(4,2),
    @BRANCH VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON; -- Prevents extra "rows affected" messages

    INSERT INTO STUDENT1(STDID, SNAME, CITY, SPI,BRANCH)
    VALUES (@STDID, @SNAME, @CITY, @SPI,@BRANCH);
END;
GO

